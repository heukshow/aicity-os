// Strict read-only registration gate for the isolated public Sandbox entry.
// No payment/registration mutation, cached approval, token return or global fetch fallback.
import { AdError } from './ad-commerce-domain.js';

const API = 'https://api-m.sandbox.paypal.com';
// PayPal may return the older Sandbox host in HATEOAS metadata; never fetch these links.
const LINK_ORIGINS = new Set([API, 'https://api.sandbox.paypal.com']);
const LIST = '/v1/notifications/webhooks';
const EVENT = 'PAYMENT.CAPTURE.COMPLETED';
const LIMIT = 65536;
const ID = /^[A-Za-z0-9_-]{1,128}$/;
const object = value => value !== null && typeof value === 'object' && !Array.isArray(value);
const keysOnly = (value, keys) => Object.keys(value).every(key => keys.includes(key));
const credential = value => typeof value === 'string' && value.length > 0 &&
  value.length <= 4096 && /^[\x21-\x7e]+$/.test(value);

class PreflightFailure extends Error {
  constructor(code) { super(code); this.code = code; }
}
const fail = code => { throw new PreflightFailure(code); };

function configuration(env, fetchImpl) {
  if (env?.PAYPAL_ENVIRONMENT !== 'sandbox' || typeof fetchImpl !== 'function' ||
      !credential(env.PAYPAL_CLIENT_ID) || env.PAYPAL_CLIENT_ID.includes(':') ||
      !credential(env.PAYPAL_CLIENT_SECRET) || typeof env.PAYPAL_WEBHOOK_ID !== 'string' ||
      !ID.test(env.PAYPAL_WEBHOOK_ID) || typeof env.SANDBOX_ORIGIN !== 'string') fail('CONFIG');
  let origin;
  try { origin = new URL(env.SANDBOX_ORIGIN); } catch { fail('CONFIG'); }
  if (origin.protocol !== 'https:' || origin.origin !== env.SANDBOX_ORIGIN ||
      origin.username || origin.password || origin.search || origin.hash ||
      origin.port || origin.hostname === 'localhost' || origin.hostname === '127.0.0.1' ||
      origin.hostname === '[::1]' || origin.hostname === 'paypal.com' ||
      origin.hostname.endsWith('.paypal.com')) fail('CONFIG');
  return { expectedUrl: origin.origin + '/sandbox/webhooks/paypal', id: env.PAYPAL_WEBHOOK_ID };
}

async function readJson(response) {
  if (response.headers.get('content-type')?.split(';')[0].trim().toLowerCase() !== 'application/json') {
    fail('RESPONSE');
  }
  const declared = response.headers.get('content-length');
  if (declared !== null && (!/^\d+$/.test(declared) || Number(declared) > LIMIT)) fail('RESPONSE');
  const reader = response.body?.getReader();
  if (!reader) fail('RESPONSE');
  const chunks = []; let length = 0;
  try {
    while (true) {
      const part = await reader.read();
      if (part.done) break;
      length += part.value.byteLength;
      if (length > LIMIT) { await reader.cancel(); fail('RESPONSE'); }
      chunks.push(part.value);
    }
  } finally { reader.releaseLock(); }
  const bytes = new Uint8Array(length); let offset = 0;
  for (const chunk of chunks) { bytes.set(chunk, offset); offset += chunk.byteLength; }
  let value;
  try { value = JSON.parse(new TextDecoder('utf-8', { fatal: true }).decode(bytes)); }
  catch { fail('RESPONSE'); }
  if (!object(value)) fail('RESPONSE');
  return value;
}

async function request(fetchImpl, path, init) {
  const url = API + path;
  // Only these literal paths are generated by this module; provider links are never followed.
  if (path !== '/v1/oauth2/token' &&
      path !== LIST + '?anchor_type=APPLICATION' && path !== LIST + '?anchor_type=ACCOUNT') fail('REQUEST');
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 10000);
  try {
    const response = await fetchImpl(url, { ...init, redirect: 'error', signal: controller.signal });
    if (!response || response.status !== 200 || response.redirected ||
        response.headers?.get('location') || (response.url && response.url !== url)) fail('RESPONSE');
    return await readJson(response);
  } catch (error) {
    if (error instanceof PreflightFailure) throw error;
    fail('PROVIDER');
  } finally { clearTimeout(timeout); }
}

function links(value, allowedRels, paths) {
  if (value === undefined) return;
  if (!Array.isArray(value) || value.length > 10) fail('REGISTRATION');
  for (const link of value) {
    if (!object(link) || !keysOnly(link, ['href', 'rel', 'method']) ||
        typeof link.href !== 'string' || !allowedRels.includes(link.rel) ||
        (link.method !== undefined && !['GET', 'POST', 'PATCH', 'PUT', 'DELETE'].includes(link.method))) {
      fail('REGISTRATION');
    }
    let url;
    try { url = new URL(link.href); } catch { fail('REGISTRATION'); }
    if (!LINK_ORIGINS.has(url.origin) || url.username || url.password || url.hash ||
        !paths.includes(url.pathname + url.search) || url.href !== link.href) fail('REGISTRATION');
  }
}

function registrationList(value, anchor, expected) {
  // Unexpected top-level fields include pagination and partial-response metadata.
  if (!object(value) || !keysOnly(value, ['webhooks', 'links']) || !Array.isArray(value.webhooks)) {
    fail('REGISTRATION');
  }
  links(value.links, ['self'], [LIST + '?anchor_type=' + anchor]);
  if (anchor === 'ACCOUNT') {
    if (value.webhooks.length !== 0) fail('ACCOUNT_NOT_EMPTY');
    return;
  }
  if (value.webhooks.length !== 1) fail('APPLICATION_COUNT');
  const hook = value.webhooks[0];
  if (!object(hook) || !keysOnly(hook, ['id', 'url', 'event_types', 'links']) ||
      hook.id !== expected.id || hook.url !== expected.expectedUrl ||
      !Array.isArray(hook.event_types) || hook.event_types.length !== 1) fail('REGISTRATION');
  const event = hook.event_types[0];
  if (!object(event) || !keysOnly(event, ['name', 'description', 'status', 'resource_versions']) ||
      event.name !== EVENT ||
      (event.description !== undefined && typeof event.description !== 'string') ||
      (event.status !== undefined && event.status !== 'ENABLED') ||
      (event.resource_versions !== undefined && (!Array.isArray(event.resource_versions) ||
        !event.resource_versions.every(version => typeof version === 'string' && version.length > 0)))) {
    fail('REGISTRATION');
  }
  const path = LIST + '/' + expected.id;
  links(hook.links, ['self', 'update', 'edit', 'delete', 'event-types'], [path, path + '/event-types']);
}

/**
 * Read current APPLICATION and ACCOUNT registrations using the supplied Sandbox credentials.
 * Every invocation performs fresh reads. The caller must gate checkout/capture on success.
 */
export async function assertSandboxWebhookRegistration(env, fetchImpl) {
  try {
    const expected = configuration(env, fetchImpl);
    const auth = await request(fetchImpl, '/v1/oauth2/token', {
      method: 'POST',
      headers: { Authorization: 'Basic ' + btoa(env.PAYPAL_CLIENT_ID + ':' + env.PAYPAL_CLIENT_SECRET),
        'Content-Type': 'application/x-www-form-urlencoded', Accept: 'application/json' },
      body: 'grant_type=client_credentials',
    });
    if (typeof auth.access_token !== 'string' || auth.access_token.length > 8192 ||
        !/^[A-Za-z0-9._~+\/-]+=*$/.test(auth.access_token) ||
        typeof auth.token_type !== 'string' || auth.token_type.toLowerCase() !== 'bearer' ||
        !Number.isSafeInteger(auth.expires_in) || auth.expires_in <= 0) fail('AUTH_RESPONSE');
    const init = { method: 'GET', headers: { Authorization: 'Bearer ' + auth.access_token, Accept: 'application/json' } };
    const application = await request(fetchImpl, LIST + '?anchor_type=APPLICATION', init);
    registrationList(application, 'APPLICATION', expected);
    const account = await request(fetchImpl, LIST + '?anchor_type=ACCOUNT', init);
    registrationList(account, 'ACCOUNT', expected);
    return { verified: true, applicationCount: 1, accountCount: 0, webhookId: expected.id,
      eventTypes: [EVENT], checkedAt: new Date().toISOString() };
  } catch (error) {
    // Neither provider bodies, URLs, thrown errors nor credentials reach the caller.
    const code = error instanceof PreflightFailure ? error.code : 'CONFIG';
    throw new AdError('PayPal Sandbox webhook preflight failed (' + code + ').', 503);
  }
}
